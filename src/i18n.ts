export const dictionaries: Record<Lang, Dict> = { en, ar };
export type TKey = keyof Dict;

export interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: TKey) => string;
  err: (code: ErrorCode) => string;
  num: (n: number) => string;
}

export function makeI18n(lang: Lang, setLang: (l: Lang) => void): I18n {
  const d = dictionaries[lang];
  // Western digits in both languages for prices (common in Saudi business documents).
  const fmt = new Intl.NumberFormat(lang === 'ar' ? 'ar-SA-u-nu-latn' : 'en-US');
  return {
    lang,
    setLang,
    t: (k) => d[k],
    err: (code) => d[`err_${code}` as TKey] ?? d.err_NETWORK,
    num: (n) => fmt.format(n),
  };
}

export const I18nContext = createContext<I18n>(makeI18n('en', () => {}));
export const useI18n = () => useContext(I18nContext);
